/**
 * Generate `packages/fixtures/src/narration/gh1.engine.graph.json` from the REAL engine (WP-02):
 * boot `createEngine` with the default UK manifest exactly as the worker and the MCP adapter do,
 * run the GH1 M-0 search, and keep the evidence nodes `storyFromEngine` reads (your-home mode).
 *
 * The engine is loaded by path at run time, so `@ibasho/ai` keeps no dependency on L1 (ARCH 3).
 * Run: `pnpm --filter @ibasho/ai gen:engine-graph` (or `-- --check` to fail on drift).
 * Owner: WP-05.
 */
import { spawnSync } from 'node:child_process';
import { readFileSync, renameSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import {
  type AnyPlugin,
  canonicalJson,
  createRegistry,
  type EngineApi,
  type IbashoModule,
} from '@ibasho/core';
import { parseTwin } from '@ibasho/core/schemas';
import { ENGINE_STORY_QUANTITIES } from '../src/evidence/engine-story.ts';

const root = new URL('../../../', import.meta.url);
const OUT = new URL('packages/fixtures/src/narration/gh1.engine.graph.json', root);
const MODULES = [
  'packs/climate/src/engine/module.ts',
  'packs/home-uk/src/engine/module.ts',
  'packs/money-uk/src/engine/module.ts',
  'packs/rules-uk/src/engine/module.ts',
];

interface EngineModule {
  createEngine(opts: {
    modules: { id: string; load: () => Promise<{ default: IbashoModule }> }[];
    allowOptions?: readonly string[];
  }): EngineApi;
  M0_OPTION_IDS: readonly string[];
}

const mods: IbashoModule[] = [];
for (const rel of MODULES)
  mods.push(((await import(new URL(rel, root).href)) as { default: IbashoModule }).default);
const eng = (await import(new URL('packages/engine/src/index.ts', root).href)) as EngineModule;
const plugins: AnyPlugin[] = [];
for (const m of mods) plugins.push(...(await m.load()));
const shared = createRegistry();
shared.registerAll(plugins);
const engine = eng.createEngine({
  modules: mods.map((m) => ({ id: m.id, load: async () => ({ default: m }) })),
  allowOptions: eng.M0_OPTION_IDS,
});
await engine.init(
  mods.map((m) => m.id),
  shared.fingerprint({ side: 'both' }),
);
const twin = parseTwin(
  JSON.parse(readFileSync(new URL('packages/fixtures/src/homes/gh1.twin.json', root), 'utf8')),
);
const job = await engine.search({
  twin,
  owner: { tenure: 'owner', discountRatePpb: 35_000_000n, horizonYears: 25 },
  target: { kind: 'default' },
  memory: { rejected: [], completed: [] },
  asOf: '2026-10-11' as Parameters<EngineApi['search']>[0]['asOf'],
});
const r = await job.result;
const nodes = r.graph.nodes
  .filter((n) => n.subject.mode === 'your-home' && ENGINE_STORY_QUANTITIES.some((re) => re.test(n.quantity)))
  .sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));
const out = {
  schema: 'ibasho.engine-graph/1',
  note: 'GH1, M-0 slice, your-home mode, trimmed to the quantities storyFromEngine reads. Generated by packages/ai/scripts/gen-engine-graph.ts from the real engine; do not edit.',
  resultHash: r.hash,
  packageIds: r.packages.ids,
  picks: r.picks,
  needsCheck: [...r.needsCheck],
  nodes,
};
const text = `${JSON.stringify(JSON.parse(canonicalJson(out)), null, 1)}\n`;
if (process.argv.includes('--check')) {
  // Compare content, not bytes: the repo formatter owns the layout.
  const have = canonicalJson(JSON.parse(readFileSync(OUT, 'utf8')));
  if (have !== canonicalJson(out)) {
    console.error('gh1.engine.graph.json is stale: run pnpm --filter @ibasho/ai gen:engine-graph');
    process.exit(1);
  }
  console.log(`gh1.engine.graph.json is current (${nodes.length} nodes, result ${r.hash.slice(0, 12)})`);
} else {
  const tmp = new URL('gh1.engine.graph.json.tmp', OUT);
  writeFileSync(tmp, text);
  renameSync(tmp, OUT);
  // Lay it out the way `pnpm lint` (Biome) expects.
  spawnSync('pnpm', ['exec', 'biome', 'format', '--write', fileURLToPath(OUT)], {
    cwd: fileURLToPath(root),
    stdio: 'ignore',
  });
  console.log(`wrote gh1.engine.graph.json (${nodes.length} nodes, result ${r.hash.slice(0, 12)})`);
}
