/**
 * Bake the seal and chapter kanji from Yuji Syuku into SVG paths (DESIGN_SYSTEM 3, F9).
 * Owner: WP-06. Run: `pnpm --filter @ibasho/ui bake-glyphs`.
 *
 * The font is fetched once from the google/fonts repository at a pinned commit, checked against
 * a pinned SHA-256 and cached in `.cache/` (git ignored). The output, `src/glyphs/baked.ts`, is
 * committed, so builds and tests never touch the network and the app never requests a font for
 * these glyphs. Yuji Syuku is licensed under the SIL Open Font License 1.1.
 */
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { parse } from 'opentype.js';
import { BAKE_LIST } from '../src/glyphs/list.ts';

const COMMIT = 'bd8f81ddb5c74d5c8897b36ad88b440266245103';
const URL_TTF = `https://raw.githubusercontent.com/google/fonts/${COMMIT}/ofl/yujisyuku/YujiSyuku-Regular.ttf`;
const SHA256 = '82728ebafc8c97391e2dab633414a806f344b8e4e2227d307179f07b548fca61';

const here = (p: string) => fileURLToPath(new URL(p, import.meta.url));
const cacheDir = here('../.cache/');
const cached = `${cacheDir}YujiSyuku-Regular.ttf`;

async function fontBytes(): Promise<Buffer> {
  if (!existsSync(cached)) {
    mkdirSync(cacheDir, { recursive: true });
    const res = await fetch(URL_TTF);
    if (!res.ok) throw new Error(`fetch ${URL_TTF}: HTTP ${res.status}`);
    writeFileSync(cached, Buffer.from(await res.arrayBuffer()));
  }
  const buf = readFileSync(cached);
  const sha = createHash('sha256').update(buf).digest('hex');
  if (sha !== SHA256) throw new Error(`Yuji Syuku SHA-256 mismatch: got ${sha}, expected ${SHA256}`);
  return buf;
}

const buf = await fontBytes();
const font = parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength) as ArrayBuffer);
const EM = 1000;
const entries: string[] = [];
for (const ch of BAKE_LIST) {
  const glyph = font.charToGlyph(ch);
  if (!glyph || glyph.index === 0) throw new Error(`Yuji Syuku has no glyph for ${ch}`);
  // Baseline at the ascender so y runs down from the top of the em box, in a 1000 unit em.
  const ascender = (font.ascender / font.unitsPerEm) * EM;
  const path = glyph.getPath(0, ascender, EM);
  const bb = path.getBoundingBox();
  const d = path.toPathData(0);
  if (!d) throw new Error(`empty path for ${ch}`);
  const box = [bb.x1, bb.y1, bb.x2 - bb.x1, bb.y2 - bb.y1].map((v) => Math.round(v * 10) / 10);
  entries.push(
    `  '${ch}': {\n    cp: 0x${ch.codePointAt(0)!.toString(16)},\n    box: [${box.join(', ')}],\n    d: '${d}',\n  },`,
  );
}

const family = font.names.fontFamily?.en ?? 'Yuji Syuku';
const version = font.names.version?.en ?? '';
const out = `/**
 * GENERATED by packages/ui/scripts/bake-glyphs.ts. Do not edit.
 * ${family} (${version}), SIL Open Font License 1.1, google/fonts@${COMMIT.slice(0, 12)}.
 * Paths are in a ${EM} unit em with y pointing down; \`box\` is the ink bounding box [x, y, w, h].
 */
import type { BakedGlyph } from './list.ts';

export const BAKED_FONT = {
  family: '${family}',
  license: 'OFL-1.1',
  sha256: '${SHA256}',
} as const;

export const BAKED_GLYPHS: Record<string, BakedGlyph> = {
${entries.join('\n')}
};
`;
const target = here('../src/glyphs/baked.ts');
writeFileSync(target, out);
console.log(`bake-glyphs: ${BAKE_LIST.length} glyphs, ${out.length} bytes to ${target}`);
