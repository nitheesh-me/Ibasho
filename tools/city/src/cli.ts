/**
 * `node tools/city/src/cli.ts fetch|build [hyderabad|london] [--refresh]` (WP-17).
 * fetch: Overpass to the committed cache. build: cache to gzip JSON tiles plus `tiles.gen.ts` in
 * the pack. Data: OpenStreetMap contributors, ODbL 1.0 (credited in the pack README and
 * ACKNOWLEDGEMENTS.md).
 */
import { createHash } from 'node:crypto';
import { mkdirSync, readdirSync, renameSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { gzipSync } from 'node:zlib';
import { AREAS } from './areas.ts';
import { buildPack } from './build.ts';
import { fetchArea } from './fetch.ts';

const here = dirname(fileURLToPath(import.meta.url));
const toolDir = join(here, '..');
const repo = join(toolDir, '..', '..');

const write = (path: string, data: string | Uint8Array) => {
  writeFileSync(`${path}.tmp`, data);
  renameSync(`${path}.tmp`, path);
};
const n = (v: number) => (v < 0 ? `m${-v}` : `${v}`);

async function main() {
  const [cmd = 'build', which = 'hyderabad', ...flags] = process.argv.slice(2);
  const area = AREAS[which];
  if (!area) throw new Error(`unknown area ${which}`);
  const cachePath = join(toolDir, area.cache);
  const json = await fetchArea(area, cachePath, flags.includes('--refresh'));
  if (cmd === 'fetch') {
    console.log(`cached ${json.elements.length} elements to ${area.cache}`);
    return;
  }
  const { tiles, stats } = buildPack(json, area);
  const out = join(repo, area.outDir);
  mkdirSync(out, { recursive: true });
  for (const f of readdirSync(out)) if (f.endsWith('.json.gz')) rmSync(join(out, f));
  const rows: string[] = [];
  let total = 0;
  for (const t of tiles) {
    const file = `t_${n(t.tx)}_${n(t.ty)}.json.gz`;
    const gz = gzipSync(Buffer.from(JSON.stringify(t)), { level: 9 });
    write(join(out, file), gz);
    total += gz.byteLength;
    const sha = createHash('sha256').update(gz).digest('hex');
    rows.push(
      `  { tx: ${t.tx}, ty: ${t.ty}, url: new URL('./tiles/${file}', import.meta.url).href, bytes: ${gz.byteLength}, sha256: '${sha}', buildings: ${t.buildings.length}, trees: ${t.trees.length} },`,
    );
  }
  const xs = tiles.map((t) => t.tx);
  const ys = tiles.map((t) => t.ty);
  const gen = `/**
 * GENERATED by tools/city (\`node tools/city/src/cli.ts build ${which}\`). Do not edit.
 * Data: OpenStreetMap contributors, ODbL 1.0. ${stats.buildings} buildings (${Object.entries(stats.bySource)
   .map(([k, v]) => `${k} ${v}`)
   .join(', ')}), ${stats.trees} trees, ${tiles.length} tiles, ${total} bytes gzip.
 */
// The pack's engine half has no DOM or Node types: declare the two globals the URLs need.
declare const URL: new (url: string, base: string) => { href: string };
declare global {
  interface ImportMeta {
    url: string;
  }
}

export const PACK_ID = '${area.packId}';
export const ORIGIN = { lat: ${area.origin.lat}, lon: ${area.origin.lon} };
export const TILE_SIZE = ${area.tileSize};
export const EXTENT = { minTx: ${Math.min(...xs)}, minTy: ${Math.min(...ys)}, maxTx: ${Math.max(...xs)}, maxTy: ${Math.max(...ys)} };
export const TILE_FILES: readonly { tx: number; ty: number; url: string; bytes: number; sha256: string; buildings: number; trees: number }[] = [
${rows.join('\n')}
];
`;
  write(join(out, '..', 'tiles.gen.ts'), gen);
  console.log(
    `${area.packId}: ${tiles.length} tiles, ${stats.buildings} buildings, ${stats.trees} trees, ${total} bytes`,
    stats.bySource,
  );
}

main().catch((e: unknown) => {
  console.error(e);
  process.exit(1);
});
