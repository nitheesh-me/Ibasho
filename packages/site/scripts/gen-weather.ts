/**
 * Builds the compact hourly weather the site worker ships with (`src/weather/*.gen.ts`).
 * Owner: WP-16. Run: `node packages/site/scripts/gen-weather.ts` from the repo root.
 *
 * - Hyderabad: Climate.OneBuilding TMYx 2011 to 2025, Rajiv Gandhi Intl AP (WMO 431285), the same
 *   EPW the Preview climate tables come from (`docs/research/v3/sources/epw/`). CC BY 4.0.
 *   GHI, DNI, DHI, dry bulb, dew point and the direct normal and diffuse horizontal illuminance
 *   columns are kept as written.
 * - London: PVGIS 5.2 TMY (JRC; SARAH2 and ERA5, 2005 to 2020), the hourly data WP-01 vendored in
 *   `packs/climate/src/engine/london-tmy-data.ts`. PVGIS gives GHI and DHI only, so DNI is
 *   (GHI - DHI) / cos(zenith) at the hour centre from the SPA (zero below 5 degrees of sun
 *   elevation, capped at 1,100 W/m2), and dew point comes from dry bulb and RH (Magnus, Alduchov
 *   and Eskridge 1996). No illuminance columns: the worker uses the Perez 1990 efficacy model.
 *
 * Encoding: comma separated integers per series (W/m2; tenths of a degree C; tens of lux).
 */
import { createHash } from 'node:crypto';
import { readFileSync, renameSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { julianDay, spa } from '../src/spa.ts';

const root = join(import.meta.dirname, '..', '..', '..');
const out = join(root, 'packages/site/src/weather');

function write(file: string, text: string) {
  const tmp = `${file}.tmp`;
  writeFileSync(tmp, text);
  renameSync(tmp, file);
}

const csv = (a: readonly number[]) => a.map((v) => String(Math.round(v))).join(',');

// Hyderabad -------------------------------------------------------------------------------
{
  const rel = 'docs/research/v3/sources/epw/IND_TG_Hyderabad-Gandhi.Intl.AP.431285_TMYx.2011-2025.epw';
  const bytes = readFileSync(join(root, rel));
  const hash = createHash('sha256').update(bytes).digest('hex');
  const lines = bytes.toString('utf8').split(/\r?\n/);
  const loc = (lines[0] ?? '').split(',');
  const rows = lines.slice(8).filter((l) => l.trim());
  if (rows.length !== 8760) throw new Error(`Hyderabad EPW has ${rows.length} rows`);
  const s = { ghi: [] as number[], dni: [] as number[], dhi: [] as number[], tdb: [] as number[], tdp: [] as number[], evdn: [] as number[], evdh: [] as number[] };
  let albedo = 0;
  for (const r of rows) {
    const c = r.split(',');
    s.tdb.push(Number(c[6]) * 10);
    s.tdp.push(Number(c[7]) * 10);
    s.ghi.push(Number(c[13]));
    s.dni.push(Number(c[14]));
    s.dhi.push(Number(c[15]));
    const evdn = Number(c[17]);
    const evdh = Number(c[18]);
    s.evdn.push(evdn >= 999900 ? -1 : evdn / 10);
    s.evdh.push(evdh >= 999900 ? -1 : evdh / 10);
    albedo += Number(c[32] ?? 0.2);
  }
  albedo = Math.round((albedo / 8760) * 100) / 100;
  write(
    join(out, 'hyderabad.gen.ts'),
    `/**
 * GENERATED by packages/site/scripts/gen-weather.ts. Do not edit.
 * Hyderabad Rajiv Gandhi Intl AP (WMO 431285), TMYx 2011 to 2025, Climate.OneBuilding.org,
 * https://climate.onebuilding.org (CC BY 4.0). sha256 of the EPW bytes: ${hash}.
 */
import type { CompactWeather } from './types.ts';

export const HYDERABAD_TMYX: CompactWeather = {
  id: 'climate.hyderabad',
  name: '${loc[1]}',
  lat: ${Number(loc[6])},
  lon: ${Number(loc[7])},
  tzHours: ${Number(loc[8])},
  elevationM: ${Number(loc[9])},
  albedo: ${albedo},
  hash: '${hash}',
  source: {
    id: 'onebuilding-tmyx-431285-2011-2025',
    title: 'Climate.OneBuilding TMYx 2011 to 2025, Hyderabad Rajiv Gandhi Intl AP (431285)',
    url: 'https://climate.onebuilding.org/WMO_Region_2_Asia/IND_India/TG_Telangana/IND_TG_Hyderabad-Gandhi.Intl.AP.431285_TMYx.2011-2025.zip',
    retrieved: '2026-10-11',
  },
  ghi: '${csv(s.ghi)}',
  dni: '${csv(s.dni)}',
  dhi: '${csv(s.dhi)}',
  dryBulbDeci: '${csv(s.tdb)}',
  dewPointDeci: '${csv(s.tdp)}',
  evdnDeca: '${csv(s.evdn)}',
  evdhDeca: '${csv(s.evdh)}',
};
`,
  );
}

// London ----------------------------------------------------------------------------------
{
  const text = readFileSync(join(root, 'packs/climate/src/engine/london-tmy-data.ts'), 'utf8');
  const grab = (k: string) => {
    const m = new RegExp(`\\b${k}: '([-0-9,]+)'`).exec(text);
    if (!m?.[1]) throw new Error(`no ${k} in London TMY`);
    return m[1].split(',').map(Number);
  };
  const T = grab('T');
  const GHI = grab('GHI');
  const DHI = grab('DHI');
  const RH = grab('RH');
  const lat = 51.51;
  const lon = -0.13;
  const s = { ghi: [] as number[], dni: [] as number[], dhi: [] as number[], tdb: [] as number[], tdp: [] as number[] };
  for (let h = 0; h < 8760; h++) {
    const doy = Math.floor(h / 24);
    const date = new Date(Date.UTC(2025, 0, 1 + doy));
    const jd = julianDay(2025, date.getUTCMonth() + 1, date.getUTCDate(), h % 24, 30, 0, 0);
    const p = spa({ jd, deltaT: 69, lat, lon, elevationM: 25, pressureMbar: 1013, tempC: 11 });
    const cz = Math.cos((p.zenith * Math.PI) / 180);
    const g = GHI[h] ?? 0;
    let d = Math.min(DHI[h] ?? 0, g);
    let b = 0;
    if (cz > 0.0872 && g > d) b = Math.min(1100, (g - d) / cz);
    else d = g;
    const t = (T[h] ?? 0) / 10;
    const rh = Math.max(1, RH[h] ?? 80);
    const gam = Math.log(rh / 100) + (17.62 * t) / (243.12 + t);
    const td = (243.12 * gam) / (17.62 - gam);
    s.ghi.push(g);
    s.dni.push(b);
    s.dhi.push(d);
    s.tdb.push(T[h] ?? 0);
    s.tdp.push(td * 10);
  }
  const hash = createHash('sha256')
    .update(JSON.stringify(s))
    .digest('hex');
  write(
    join(out, 'london.gen.ts'),
    `/**
 * GENERATED by packages/site/scripts/gen-weather.ts. Do not edit.
 * London PVGIS 5.2 TMY (JRC European Commission; SARAH2 radiation, ERA5 meteorology, 2005 to
 * 2020), https://re.jrc.ec.europa.eu/api/v5_2/tmy?lat=51.51&lon=-0.13, as vendored by WP-01 in
 * packs/climate. DNI derived from GHI and DHI with the SPA; dew point from dry bulb and RH.
 * sha256 of the series JSON: ${hash}.
 */
import type { CompactWeather } from './types.ts';

export const LONDON_PVGIS_TMY: CompactWeather = {
  id: 'climate.london',
  name: 'London PVGIS TMY',
  lat: ${lat},
  lon: ${lon},
  tzHours: 0,
  elevationM: 25,
  albedo: 0.2,
  hash: '${hash}',
  source: {
    id: 'pvgis-5-2-tmy-london',
    title: 'PVGIS 5.2 typical meteorological year, London (51.51 N, 0.13 W), SARAH2 and ERA5 2005 to 2020',
    url: 'https://re.jrc.ec.europa.eu/api/v5_2/tmy?lat=51.51&lon=-0.13&outputformat=json',
    retrieved: '2026-10-11',
  },
  ghi: '${csv(s.ghi)}',
  dni: '${csv(s.dni)}',
  dhi: '${csv(s.dhi)}',
  dryBulbDeci: '${csv(s.tdb)}',
  dewPointDeci: '${csv(s.tdp)}',
};
`,
  );
}
console.log('gen-weather: wrote hyderabad.gen.ts and london.gen.ts');
