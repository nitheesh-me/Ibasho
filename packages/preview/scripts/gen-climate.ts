/**
 * Monthly climate tables for the Preview model, derived from the Hyderabad TMYx EPW
 * (climate.onebuilding.org, IND_TG_Hyderabad-Gandhi.Intl.AP.431285_TMYx.2011-2025, CC BY 4.0).
 * London values are CIBSE-like monthly means (estimate) until WP-01 exposes the London TMY.
 * Run: `node scripts/gen-climate.ts`. Writes `src/model/climate.gen.ts`.
 */
import { readFileSync, renameSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = join(import.meta.dirname, '..', '..', '..');
const epw = join(
  root,
  'docs/research/v3/sources/epw/IND_TG_Hyderabad-Gandhi.Intl.AP.431285_TMYx.2011-2025.epw',
);
const lines = readFileSync(epw, 'utf8')
  .split(/\r?\n/)
  .slice(8)
  .filter((l) => l.trim());
const t = Array.from({ length: 12 }, () => ({ n: 0, tC: 0, ghi: 0, dni: 0, dhi: 0, rh: 0 }));
for (const l of lines) {
  const c = l.split(',');
  const mo = Number(c[1]) - 1;
  const r = t[mo];
  if (!r) continue;
  r.n++;
  r.tC += Number(c[6]);
  r.rh += Number(c[8]);
  r.ghi += Number(c[13]);
  r.dni += Number(c[14]);
  r.dhi += Number(c[15]);
}
const f1 = (x: number) => Math.round(x * 10) / 10;
const hyd = {
  tC: t.map((r) => f1(r.tC / r.n)),
  rhPct: t.map((r) => Math.round(r.rh / r.n)),
  ghiKwhM2: t.map((r) => f1(r.ghi / 1000)),
  dniKwhM2: t.map((r) => f1(r.dni / 1000)),
  dhiKwhM2: t.map((r) => f1(r.dhi / 1000)),
};
const src = `/**
 * GENERATED by packages/preview/scripts/gen-climate.ts. Do not edit.
 * Hyderabad: monthly means and totals from the TMYx 2011-2025 EPW (Rajiv Gandhi Intl, 431285),
 * climate.onebuilding.org, CC BY 4.0. London: monthly estimates (CIBSE-like), grade estimate.
 */
export interface MonthlyClimate {
  id: string;
  lat: number;
  /** Monthly mean dry bulb, degC. */
  tC: readonly number[];
  rhPct: readonly number[];
  /** Monthly totals, kWh/m². */
  ghiKwhM2: readonly number[];
  dniKwhM2: readonly number[];
  dhiKwhM2: readonly number[];
  source: string;
}

export const CLIMATES: Readonly<Record<string, MonthlyClimate>> = {
  'climate.hyderabad': {
    id: 'climate.hyderabad',
    lat: 17.45,
    tC: ${JSON.stringify(hyd.tC)},
    rhPct: ${JSON.stringify(hyd.rhPct)},
    ghiKwhM2: ${JSON.stringify(hyd.ghiKwhM2)},
    dniKwhM2: ${JSON.stringify(hyd.dniKwhM2)},
    dhiKwhM2: ${JSON.stringify(hyd.dhiKwhM2)},
    source: 'TMYx 2011-2025 IND_TG_Hyderabad-Gandhi.Intl.AP.431285 (climate.onebuilding.org)',
  },
  'climate.london': {
    id: 'climate.london',
    lat: 51.5,
    tC: [5.2, 5.3, 7.6, 9.9, 13.3, 16.5, 18.7, 18.5, 15.7, 12.0, 8.0, 5.5],
    rhPct: [86, 82, 77, 72, 70, 69, 69, 71, 76, 81, 85, 87],
    ghiKwhM2: [20, 35, 70, 110, 145, 150, 150, 125, 90, 55, 27, 17],
    dniKwhM2: [25, 40, 70, 105, 130, 125, 130, 115, 95, 60, 32, 20],
    dhiKwhM2: [13, 22, 40, 58, 75, 82, 80, 68, 48, 30, 17, 11],
    source: 'estimate (CIBSE-like London monthly means)',
  },
};
`;
const out = join(import.meta.dirname, '..', 'src/model/climate.gen.ts');
writeFileSync(`${out}.tmp`, src);
renameSync(`${out}.tmp`, out);
