/**
 * Mean day per month (24 hourly values) for the real energy stage's built-in weather (WP-18).
 * Hyderabad: TMYx 2011-2025 EPW (climate.onebuilding.org, CC BY 4.0), local standard time IST.
 * London: PVGIS 5.2 TMY (JRC) from packs/climate, UTC. Values: dry bulb (0.1 degC), GHI and DHI
 * (Wh/m2 in the hour), RH (%). Run: `node packs/types-in/scripts/gen-weather.ts`.
 * Writes packages/engine/src/zones/weather.gen.ts. When the site context carries a full EPW the
 * engine uses all 8,760 hours instead.
 */
import { readFileSync, renameSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { LONDON_TMY } from '../../climate/src/engine/london-tmy-data.ts';

const root = join(import.meta.dirname, '..', '..', '..');
const DAYS = [31, 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31];

interface Hourly {
  t: number[];
  ghi: number[];
  dhi: number[];
  rh: number[];
}

function meanDays(h: Hourly) {
  const out = { t: [] as number[], ghi: [] as number[], dhi: [] as number[], rh: [] as number[] };
  let hour = 0;
  for (let m = 0; m < 12; m++) {
    const n = DAYS[m] as number;
    for (let k = 0; k < 24; k++) {
      let st = 0;
      let sg = 0;
      let sd = 0;
      let sr = 0;
      for (let d = 0; d < n; d++) {
        const i = hour + d * 24 + k;
        st += h.t[i] as number;
        sg += h.ghi[i] as number;
        sd += h.dhi[i] as number;
        sr += h.rh[i] as number;
      }
      out.t.push(Math.round((st / n) * 10));
      out.ghi.push(Math.round(sg / n));
      out.dhi.push(Math.round(sd / n));
      out.rh.push(Math.round(sr / n));
    }
    hour += n * 24;
  }
  return out;
}

const epw = readFileSync(
  join(root, 'docs/research/v3/sources/epw/IND_TG_Hyderabad-Gandhi.Intl.AP.431285_TMYx.2011-2025.epw'),
  'utf8',
)
  .split(/\r?\n/)
  .slice(8)
  .filter((l) => l.trim())
  .map((l) => l.split(','));
const hyd = meanDays({
  t: epw.map((c) => Number(c[6])),
  ghi: epw.map((c) => Number(c[13])),
  dhi: epw.map((c) => Number(c[15])),
  rh: epw.map((c) => Number(c[8])),
});
const num = (s: string, k: number) => s.split(',').map((x) => Number(x) / k);
const lon = meanDays({
  t: num(LONDON_TMY.T, 10),
  ghi: num(LONDON_TMY.GHI, 1),
  dhi: num(LONDON_TMY.DHI, 1),
  rh: num(LONDON_TMY.RH, 1),
});

const block = (name: string, meta: string, d: ReturnType<typeof meanDays>) => `  '${name}': {
${meta}
    tDeci: [${d.t.join(',')}],
    ghi: [${d.ghi.join(',')}],
    dhi: [${d.dhi.join(',')}],
    rh: [${d.rh.join(',')}],
  },`;

const src = `/**
 * GENERATED by packs/types-in/scripts/gen-weather.ts. Do not edit.
 * Mean day per month, 12 x 24 hours from January, for the real energy stage (WP-18).
 * Hyderabad: TMYx 2011-2025, Rajiv Gandhi Intl 431285 (climate.onebuilding.org, CC BY 4.0), IST.
 * London: PVGIS 5.2 TMY (JRC, SARAH2 and ERA5 2005 to 2020), UTC.
 * tDeci: dry bulb in tenths of a degree C; ghi, dhi: Wh/m2 in the hour; rh: percent.
 */
export interface MeanDayWeather {
  id: string;
  lat: number;
  lon: number;
  /** Clock offset from UTC, hours. */
  tzHours: number;
  tDeci: readonly number[];
  ghi: readonly number[];
  dhi: readonly number[];
  rh: readonly number[];
  source: string;
}

export const MEAN_DAY_WEATHER: Readonly<Record<string, MeanDayWeather>> = {
${block('climate.hyderabad', "    id: 'climate.hyderabad',\n    lat: 17.45,\n    lon: 78.43,\n    tzHours: 5.5,\n    source: 'TMYx 2011-2025 IND_TG_Hyderabad-Gandhi.Intl.AP.431285',", hyd)}
${block('climate.london', "    id: 'climate.london',\n    lat: 51.51,\n    lon: -0.13,\n    tzHours: 0,\n    source: 'PVGIS 5.2 TMY London',", lon)}
};
`;
const out = join(root, 'packages/engine/src/zones/weather.gen.ts');
writeFileSync(`${out}.tmp`, src);
renameSync(`${out}.tmp`, out);
console.log('wrote', out, src.length, 'bytes');
