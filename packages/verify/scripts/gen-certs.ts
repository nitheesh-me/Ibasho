/**
 * Writes the GH1 golden certificate and the M-0 mutants to `packages/fixtures/src/certs/`.
 * Owner: WP-04. Run with `pnpm --filter @ibasho/verify gen:certs`.
 */
import { mkdirSync, renameSync, writeFileSync } from 'node:fs';
import { buildGolden, buildMutant, CERT_DIR, certJson, MUTANTS } from '../test/gh1-certs.ts';

function writeAtomic(path: string, body: string): void {
  writeFileSync(`${path}.tmp`, body);
  renameSync(`${path}.tmp`, path);
}

mkdirSync(CERT_DIR, { recursive: true });
const golden = await buildGolden();
writeAtomic(`${CERT_DIR}/gh1-m0.cert.json`, certJson(golden));
for (const m of MUTANTS) writeAtomic(`${CERT_DIR}/${m.file}`, certJson(buildMutant(golden, m.file)));
writeAtomic(
  `${CERT_DIR}/manifest.json`,
  certJson({
    schema: 'ibasho.cert-fixtures/1',
    note: 'Generated by pnpm --filter @ibasho/verify gen:certs; do not edit.',
    golden: 'gh1-m0.cert.json',
    mutants: MUTANTS,
  }),
);
console.log(`wrote ${2 + MUTANTS.length} files to ${CERT_DIR}`);
